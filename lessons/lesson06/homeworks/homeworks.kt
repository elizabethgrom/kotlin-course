    fun recommendClothes(temperature: Double) {
        if (temperature < -30 || temperature > 35) {
            println("Температура $temperature°C → Не выходить из дома")
        } else if (temperature < 10) {
            println("Температура $temperature°C → Куртка и шапка")
        } else if (temperature <= 18) {
            println("Температура $temperature°C → Ветровка")
        } else {
            println("Температура $temperature°C → Футболка и шорты")
        }
    }

