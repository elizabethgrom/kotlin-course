   // Клиенты интернет-магазина получают бонусные баллы за покупки. Напишите функцию,
   // которая принимает сумму покупки и печатает в консоль количество бонусных баллов:
    //2 балла за каждые 100 рублей при сумме покупки до 1000 рублей и 3 балла за каждые 100 рублей при сумме свыше этого.

    fun calcBonus(amount: Double) {
        if (amount < 0) {
            println("Ошибка: сумма покупки не может быть отрицательной")
            return
        }

        val hundreds = (amount / 100).toInt()

        val bonus = when {
            amount <= 1000 -> hundreds * 2
            else           -> hundreds * 3
        }

        println("Сумма покупки: $amount руб. → $bonus бонусных баллов")
    }

    //Задание 5: "Определение типа документа"
//
//В системе хранения документов каждый файл имеет расширение. Напишите функцию,
// которая на основе расширения файла печатает в консоль его тип:
// "Текстовый документ", "Изображение", "Таблица" или "Неизвестный тип".

    fun detectDocType(fileName: String) {
        val ext = fileName.substringAfterLast('.', "").lowercase()

        val type = when (ext) {
            "txt", "doc", "docx", "pdf"          -> "Текстовый документ"
            "jpg", "jpeg", "png", "gif", "bmp"   -> "Изображение"
            "xls", "xlsx", "csv"                 -> "Таблица"
            else                                 -> "Неизвестный тип"
        }

        println("Файл '$fileName' → $type")
    }

    fun main() {
        detectDocType("report.docx")   // Текстовый документ
        detectDocType("photo.PNG")     // Изображение
        detectDocType("data.xlsx")     // Таблица
        detectDocType("song.mp3")      // Неизвестный тип
        detectDocType("README")        // Неизвестный тип (нет расширения)
    }

